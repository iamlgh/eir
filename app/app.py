@app.route('/fb_webhook', methods=['GET', 'POST'])
def fb_webhook():
    logger.info('Received fb_webhook call')
    if request.method == 'GET':
        # Handle Meta's initial handshake/verification
        mode = request.args.get('hub.mode')
        token = request.args.get('hub.verify_token')
        challenge = request.args.get('hub.challenge')

        if mode == 'subscribe' and token == os.environ.get('VERIFY_TOKEN'):
            logger.info('Webhook successfully verified by Meta!')
            return challenge, 200
        return 'Verification mismatch', 403

    if request.method == 'POST':
        logger.info('Received post request from Facebook')

        # Grab raw request data for signature verification
        raw_payload = request.get_data()
        signature_header = request.headers.get('X-Hub-Signature-256')

        # Run security check
        if not verify_fb_signature(raw_payload, signature_header):
            logger.warning('Unauthorized POST request: Signature verification failed!')
            return 'Invalid signature', 403

        # Safely convert raw bytes to JSON now that it's verified
        data = request.get_json()
        logger.debug(f'Full webhook payload received:\n{json.dumps(data, indent=2)}')
        if data.get('object') == 'page':
            for entry in data.get('entry', []):
                for messaging_event in entry.get('messaging', []):
                    sid = messaging_event.get('sender', {}).get('id')
                    if sid and 'message' in messaging_event:
                        message_text = messaging_event['message'].get('text', '').strip()
                        spam_keywords = ['fund', 'grant', 'prince', 'money', 'inheritance', 'million', 'usd']
                        is_spam = any(keyword in message_text for keyword in spam_keywords)
                        if is_spam:
                            logger.info('Spam detected and silently dropped.')
                            return 'EVENT_RECEIVED', 200

                        logger.debug('Not detected as spam.')
                        messenger_success = False
                        locale = 'da'
                        if sid == '38506813588909426':
                            locale = 'en'
                        name = i18n.t('app.coach', locale=locale)
                        r = get_fb_user_info(sid)
                        if r:
                            # store code in database with sid and name, and a timestamp for expiration (e.g. 10 minutes)
                            name = r.get('first_name', '') + ' ' + r.get('last_name', '')
                            name = name.strip()
                            # locale = r.get('locale', 'da').split('-')[0] #requires pages_user_locale permissions
                        if re.match(r'^\s*link\s*Eir\s*$', message_text, re.IGNORECASE):
                            logger.debug('Message matches linking request')
                            # get info from sid using graph api and send a message back to the user
                            # generate a random 6 digit code
                            # code = ''.join(random.choices(string.ascii_uppercase + string.digits, k=6))
                            code = ''.join(secrets.choice('0123456789') for _ in range(6))
                            res: str = save_pending_link(sid, code, name, 'facebook')

                            # send response back to the user with the code
                            if res == code:
                                messenger_success = send_fb_messenger_response(
                                    sid, i18n.t('app.service_link_code', code=code, name=name, service_name='Facebook', locale=locale)
                                )
                            else:
                                # res is a string value for a localized error message
                                messenger_success = send_fb_messenger_response(sid, i18n.t(res, locale=locale))
                        elif re.match(r'^\s*(afmeldinger|signouts)\s*$', message_text, re.IGNORECASE):
                            logger.debug('Message matches update request')

                            # get signouts that match coaches teams for today
                            try:
                                content = ''
                                notifications: list[models.Notification] = get_notifications_by_sid(sid, 'facebook')
                                if not notifications:
                                    content = i18n.t('app.no_link_found', name=name, service_name='Facebook', locale=locale)
                                else:
                                    team_ids: list = notifications[0].team_ids or []
                                    if not team_ids:
                                        content = i18n.t('app.no_teams_found', name=name, service_name='Facebook', locale=locale)
                                    else:
                                        current_date = datetime.now().strftime('%Y-%m-%d')
                                        for team_id in team_ids:
                                            logger.debug(f'get_signout_list_from_db for team {team_id}')
                                            team_signouts: list[models.Signout] = get_signout_list_from_db(
                                                current_date, CONVENTUS_CLUB_ID, CONVENTUS_DEPT_ID.split('_')[-1], team_id
                                            )
                                            paired_name = get_pairing_from_team_id(team_id) or team_id
                                            if len(team_signouts) > 0:
                                                logger.debug(f'get_signout_list_from_db for team {team_id} returned {len(team_signouts)} signouts')
                                                content += f'{i18n.t("app.signout_response", team_id=paired_name, count=len(team_signouts), locale=locale)}\n'
                                                content += create_signout_details_for_coach(team_id, team_signouts)
                                            # else:
                                            #    content += f'{i18n.t("app.signout_response", team_id=paired_name, count="0")}\n'
                                        if content == '':
                                            content = i18n.t('app.no_signouts_today', locale=locale)
                            except DatabaseError as e:
                                logger.error(f'Database error occurred while fetching notifications for SID {sid}: {e}')
                                content += i18n.t('app.database_error', locale=locale)
                            except Exception as e:
                                logger.error(f'Error occurred while fetching notifications for SID {sid}: {e}')
                                content += i18n.t('app.unknown_error', locale=locale)

                            # send response back to the user with the signouts
                            messenger_success = send_fb_messenger_response(sid, content)
                        else:
                            logger.warning(f'Unrecognized message from user {sid}: {message_text}')
                        logger.info(f'FB Messenger send result: {"Success" if messenger_success else "Failed"}')  # {' checked' if checked else ''}
        return 'EVENT_RECEIVED', 200


