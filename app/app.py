@app.route('/login', methods=['POST'])
def coach_login():
    logger.debug('Running coach login')
    username = request.form.get('username')
    password = request.form.get('password')

    # skip authentication if username or password is not set
    if not username or not password:
        flash(i18n.t('app.credentials_failed'), 'danger')
        return redirect(url_for('login_c'))

    # Conventus authentication
    r: LoginResult = conventus.coach_login(username, password, CONVENTUS_CLUB_NAME, request.headers)
    home_page = r.get('home_page')
    cookies = r.get('cookies')

    if r.get('login_success') and cookies is not None and home_page is not None:
        logger.info('Coach authenticated successfully')
        session.permanent = True  # persistent cookie lasting Flask's default 31 days
        session['username'] = username
        logger.trace(f'Added to session: {session["username"]}')
        session['PHPSESSID'] = cookies.get('PHPSESSID')
        logger.trace(f'Added to session: {session["PHPSESSID"]}')

        # fix teams, else use the teams from the homepage
        team_tds: ResultSet[Tag] = conventus.get_team_tds(home_page)
        logger.debug(f'Found {len(team_tds)} team tds')
        logger.trace(f'Team tds: {team_tds}')
        session['teams'] = conventus.extract_teams(team_tds)
        if not session['teams']:
            logger.warning(f'Coach {username} logged in with no teams assigned')
            flash(i18n.t('app.no_teams_assigned'), 'warning')
            session.pop('username', None)
            session.pop('teams', None)
            return redirect(url_for('login_c'))
        logger.trace(f'Added to session: {session["teams"]}')
        return redirect(url_for('main_menu', user=username))  # Redirect to the menu function and pass the username
    else:
        forwarded = request.headers.get('X-Forwarded-For', '')
        ip = forwarded.split(',')[0].strip() if forwarded else request.remote_addr
        logger.warning(f'Failed login attempt from ip: {ip}')
        flash(i18n.t('app.credentials_failed'), 'danger')
        return redirect(url_for('login_c'))


