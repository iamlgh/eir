def checkin_team(team_name: str, date: str, user: str) -> ResponseReturnValue:
    logger.debug('Team check-in')
    content = ''
    try:
        team_id = team_ref_to_id(team_name)
        logger.debug(team_id)
        s = set_session_cookie_for_requests()
        logger.trace(s.cookies)

        # get team lists for the date
        all_team_content: list = []
        for team_id in team_id.split(','):
            # r: RequestsResponse = conventus.get_team_checkin_lists(team_id, s.cookies, request.headers)
            r: requests.Response = conventus.get_team_checkin_lists(team_id, s.cookies, request.headers)
            list_id: str = conventus.find_team_checkin_list_id_from_content(team_id, date, r.content)
            logger.debug(f'list ID: {list_id}')
            if list_id == '':
                # no list exists, create new list for the team and date, then get the new list id
                logger.debug(f'Creating new check-in list for {team_name} (id: {team_id}) on {date}')
                list_id = conventus.add_checkin_list(s.cookies, team_id, date, request.headers)
            if list_id:
                checkin_list_content: str = conventus.get_checkin_list(s.cookies, team_id, date, list_id, request.headers)
                logger.debug('start find_member_checkins')
                member_checkins: list[dict] = conventus.find_member_checkins(team_id, date, checkin_list_content)
                logger.debug('end find_member_checkins')
                if len(member_checkins) and member_checkins[0] == {'db_available': False}:
                    member_checkins.pop(0)
                    flash(i18n.t('app.signout_db_unavailable'), 'danger')
                logger.trace(f'Check-ins: {member_checkins}')
                team_content = ''
                for ci in member_checkins:
                    # {'member_id': member_id, 'member_name': member_name_norm, 'status': status}
                    # <input type="checkbox" id="ci_nnnnnnn" name="ci_nnnnnnn" value="nnnnnnn" onclick="member_clicked(nnnnnnn, 2, list_id);">
                    checked = ''
                    info = ''
                    member_id = ci.get('member_id')
                    status = ci.get('status', '')
                    if status == 'checked-in':
                        checked = ' checked'
                    elif status == i18n.t('app.checked_in'):
                        checked = ' checked'
                    if 'signed-out' in status:
                        status = status.replace('signed-out', i18n.t('app.signed_out'))  # l10n
                        info = f': <span style="color: red" id="so_{member_id}">{status}</span>'
                    elif status == i18n.t('app.signed_out'):
                        info = f': <span style="color: red" id="so_{member_id}">{status}</span>'
                    team_content += f'''<input type="checkbox" id="ci_{member_id}" name="ci_{member_id}" value="{member_id}"{checked} onclick="member_clicked({member_id}, 2, {list_id});">
                    <label for="ci_{member_id}" onclick="$('ci_{member_id}').click();"> {ci.get('member_name')}{info}</label><br>
                    '''
                if team_content:
                    team_content = f'<p>{team_content}</p>'
                all_team_content.append(team_content)
        if all_team_content:
            content = '<hr />'.join(all_team_content)
    except SessionError:
        logger.debug(f'Session {session.get("teams")}')
        flash(i18n.t('app.session_error'), 'danger')
        return redirect(url_for('checkin_menu', user=user))
    except SiteError as e:
        flash(f'{i18n.t("app.site_error")} ({e})', 'danger')
        return redirect(url_for('checkin_menu', user=user))
    except ParsingError:
        flash(i18n.t('app.parsing_error'), 'danger')
        return redirect(url_for('checkin_menu', user=user))
    return render_template('checkin_team.html', user=user, team=team_name, date=date, content=content)


