def member_updates(user: str) -> ResponseReturnValue:
    """
    Lookup member updates for the teams in the session. If no teams are in the session, it will attempt to read the home page and extract the teams.
    """
    logger.debug('Running member_updates')
    s = set_session_cookie_for_requests()

    if not session.get('teams'):
        # read home page and check for changes in team members
        username = session.get('username')
        if username and session.get('PHPSESSID'):
            admin_username = os.environ.get('ADMIN')
            if admin_username and username == admin_username:
                # get all teams in dept for admin user
                logger.info('Admin user detected')
                content = conventus.read_checkin_list_start_page(request.headers, s.cookies)
                logger.trace(content)
                session['teams'] = conventus.parse_checkin_list_start_page(content)
            else:
                home_page = conventus.get_home_page(s.cookies, request.headers)
                team_tds: ResultSet[Tag] = conventus.get_team_tds(home_page)
                logger.debug(f'Found {len(team_tds)} team tds')
                logger.trace(f'Team tds: {team_tds}')
                session['teams'] = team_tds

    content = ''
    if session.get('teams'):
        logger.debug(f'Teams in session: {session.get("teams")}')
        send_notifications: int = 0
        if request.args.get('notify'):
            send_notifications = int(request.args.get('notify'))
        content = conventus.check_for_added_and_removed_members_by_teams(
            session.get('teams'), headers=request.headers, cookies=s.cookies, group_results=True, send_notifications=send_notifications
        )
    else:
        flash(i18n.t('app.site_error'), 'danger')
        return redirect(url_for('main_menu', user=user))
    return render_template('member_updates.html', user=user, content=content)


def team_menu_logic() -> tuple:
    # display "team", e.g. Hold 65 (or paired name, e.g. Hold 31 & 32) for coaches
    teams = session.get('teams', [])
    logger.debug(f'Received from session: {teams}')
    date = datetime.now().strftime('%Y-%m-%d')
    team_refs_after_pairing = []
    for t in teams:
        logger.debug(f'Processing team: {t}')
        ref = get_pairing(t)
        if ref is None:
            ref = t.get('ref')
        if ref not in team_refs_after_pairing:
            team_refs_after_pairing.append(ref)
        if t.get('ref') != ref:
            logger.debug(f'Team {t.get("ref")} is paired as {ref}')
    return team_refs_after_pairing, date


