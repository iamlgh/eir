@app.route('/notification_link', methods=['POST'])
@require_session_keys('PHPSESSID', 'username', 'teams', redirect_to='login_c')
def notification_link():
    logger.info('Linking started')
    # grab the submitted code from the form
    service: str = request.form.get('service')
    service_name: str = service.title()
    raw_code: str = request.form.get('linking_code')

    # strip absolutely ALL whitespace (spaces, tabs, newlines) using Regex
    code = re.sub(r'\s+', '', raw_code)

    if not code or len(code) != 6:
        flash(i18n.t('app.invalid_code'), 'danger')
        return redirect(request.referrer or url_for('home'))

    # get info from db about the code, and if valid, add to db for this user
    doc = models.PendingLink.objects(code=code, service=service).first()
    if not doc:
        docs = models.PendingLink.objects(service=service)
        logger.debug(f'Pending: {len(docs)}')
        for d in docs:
            logger.trace(d)
        flash(i18n.t('app.expired_code'), 'danger')
        return redirect(request.referrer or url_for('home'))

    # add all team ids for this user to the db, so they can get notifications for all their teams
    teams = session.get('teams') or []
    team_ids: list[str] = []
    for team in teams:
        team_id = team.get('id')
        if team_id:
            team_ids.append(team_id)

    lingua: str = request.form.get('lingua')
    if not lingua:
        lingua = get_locale()

    if doc.sid:
        success = setup_notification(
            sid=doc.sid, username=session.get('username'), club_id=CONVENTUS_CLUB_ID, team_ids=team_ids, service=service, lingua=lingua
        )  # club_id=session.get('club_id')
    if not success:
        flash(i18n.t('app.notification_setup_failed', service_name=service_name), 'danger')
        return redirect(request.referrer or url_for('home'))

    # create the success notifications
    if service == 'facebook':
        send_fb_messenger_response(
            doc.sid, i18n.t('app.notifications_linked', name=doc.name, club_name=CONVENTUS_CLUB_NAME, service_name=service_name)
        )
    else:
        send_telegram_message(doc.sid, i18n.t('app.notifications_linked', name=doc.name, club_name=CONVENTUS_CLUB_NAME, service_name=service_name))
    flash(i18n.t('app.success_notifications_linked', service_name=service_name), 'success')

    # delete the pending link from the database
    doc.delete()

    # redirect back to the exact page the user came from
    # Fallback to 'home' if the referrer header is missing
    return redirect(request.referrer or url_for('home'))


