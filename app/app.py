@app.route('/member_login_go', methods=['POST'])
def member_login() -> ResponseReturnValue:
    login_type = request.form.get('log_ind_med')
    phone_country = request.form.get('mobil_land')
    phone_no = request.form.get('mobil')
    email = request.form.get('email')
    password = request.form.get('password')
    club_id = CONVENTUS_CLUB_ID

    if login_type == 'mobil':
        if not phone_no or not password:
            logger.warning(f'Invalid parameters for {login_type}: {phone_no}')
            flash(i18n.t('app.member_credentials_failed', login_type=login_type), 'danger')
            return redirect(url_for('login_m'))
    else:
        if not email or not password:
            logger.warning(f'Invalid parameters for {login_type}: {email}')
            flash(i18n.t('app.member_credentials_failed', login_type=login_type), 'danger')
            return redirect(url_for('login_m'))

    cookies, selectable_profiles, login_success = conventus.member_login(
        password, club_id, login_type, request.headers, email, phone_country, phone_no, session.get('member_sessid')
    )
    session.permanent = True  # persistent cookie lasting Flask's default 31 days
    logger.debug(f'Selectable profiles: {selectable_profiles} ({len(selectable_profiles)})')
    logger.debug(f'Login successful: {login_success}')
    if login_success and len(selectable_profiles) == 1:
        # set user session
        # session['selectable_profiles'] = selectable_profiles  # uncomment and then login to use for testing
        logger.debug(f'Profile: {selectable_profiles[0]}')
        session['member_sessid'] = cookies.get('PHPSESSID')
        session['club_id'] = club_id
        logger.debug(f'Added to session: club_id: {session["club_id"]}')
        member_id: str = selectable_profiles[0].get('member_id')
        session['member_id'] = member_id
        logger.debug(f'Added to session: member_id: {session["member_id"]}')
        name: str = selectable_profiles[0].get('name')
        session['name'] = name
        session['member_teams'] = selectable_profiles[0].get('teams')
        logger.debug(f'Added to session: member_teams: {session["member_teams"]}')
        logger.info('redirect to member_menu')
        return redirect(url_for('member_menu'))  # Redirect to the menu function
    elif login_success and selectable_profiles:
        # set user session
        session['member_sessid'] = cookies.get('PHPSESSID')
        session['club_id'] = club_id
        logger.debug(f'Added to session: {session["club_id"]}')
        session['selectable_profiles'] = selectable_profiles
        logger.debug(f'Added to session: {session["selectable_profiles"]}')
        logger.info('redirect to member_profile_select')
        return redirect(url_for('member_profile_select'))
    elif login_success:
        # logged in to conventus, but no members of the login are a current team member of a valid team
        # session.clear() not used because the session id can be used for both member and coach in the same browser
        session.pop('member_teams', None)
        session.pop('member_id', None)
        session.pop('club_id', None)
        session.pop('name', None)
        session.pop('selectable_profiles', None)
        logger.warning('Login successful, but no team members in valid "depts" found in any profile')
        flash(i18n.t('app.no_profiles'), 'danger')
        return redirect(url_for('login_m'))
    else:
        # TODO anonymize logging of failed login attempts
        logger.warning(f'Failed login attempt for {login_type}: {phone_no if login_type == "mobil" else email}')
        flash(i18n.t('app.member_credentials_failed', login_type=login_type), 'danger')
        return redirect(url_for('login_m'))


