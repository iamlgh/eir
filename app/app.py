def verify_fb_signature(raw_payload_bytes, signature_header):
    """
    Verifies that the incoming webhook payload was signed by Meta using your App Secret.
    """
    if not signature_header:
        return False

    # Strip "sha256=" from the header prefix to isolate the actual signature
    received_signature = signature_header.replace('sha256=', '')
    app_secret = os.environ.get('FB_APP_SECRET')
    if not app_secret:
        logger.error('FB_APP_SECRET not set; rejecting webhook payload')
        return False

    # Calculate the expected signature using your App Secret and raw body bytes
    expected_signature = hmac.new(key=app_secret.encode('utf-8'), msg=raw_payload_bytes, digestmod=hashlib.sha256).hexdigest()

    # Secure, timing-safe comparison
    return hmac.compare_digest(expected_signature, received_signature)


