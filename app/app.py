def require_session_keys(*keys, redirect_to='login_c'):
    def decorator(f):
        @wraps(f)
        def wrapper(*args, **kwargs):
            if request.method == 'OPTIONS':
                return f(*args, **kwargs)  # no session keys to verify for OPTIONS
            missing = [key for key in keys if not session.get(key)]
            if missing:
                logger.debug(f'Missing or empty session keys: {missing}, redirecting to login')
                flash(i18n.t('app.no_active_session'), 'danger')
                return redirect(url_for(redirect_to))
            return f(*args, **kwargs)

        return wrapper

    return decorator


@app.before_request
def enforce_session_expiry():
    expires_at = session.get('expires_at')
    if expires_at is not None:
        # datetimes pulled back out of the session are already tz-aware, if they were stored tz-aware
        if datetime.now(timezone.utc) >= expires_at:
            session.clear()
            # optionally: flash a message, redirect to login, etc.
            flash(i18n.t('app.session_expired'), 'danger')


