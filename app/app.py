def send_fb_messenger_response(recipient_id: str, text_content: str) -> bool:
    """
    Sends a standard text reply to a Messenger user using the Send API.
    """
    url = 'https://graph.facebook.com/v26.0/me/messages'
    params = {'access_token': PAGE_ACCESS_TOKEN}
    payload: dict = {'recipient': {'id': recipient_id}, 'messaging_type': 'RESPONSE', 'message': {'text': text_content}}

    try:
        response = requests.post(url, params=params, json=payload, timeout=REQUEST_TIMEOUT)
        response_data = response.json()

        if response.status_code == 200:
            logger.info(f'Successfully sent message to {recipient_id}')
            return True
        else:
            logger.error(f'Failed to send message: {response_data}')
            return False

    except Exception as e:
        logger.error(f'Error calling Messenger Send API: {e}')
        return False


