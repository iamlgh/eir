@app.route('/telegram_webhook', methods=['POST'])
def telegram_webhook():
    payload = request.get_json()
    logger.trace(f'Full webhook payload received:\n{json.dumps(payload, indent=2)}')
    if 'message' in payload and 'text' in payload['message']:
        chat_id = payload['message']['chat']['id']
        text = payload['message']['text'].strip()
        user_info = payload['message']['from']

        first_name = user_info.get('first_name', '')
        last_name = user_info.get('last_name', '')
        name = f'{first_name} {last_name}'.strip()

        try:
            # Telegram delivers deep links as "/start <parameter>"
            if text == '/start linkeir':
                # generate secure random 6-digit code
                # code = ''.join(random.choices(string.ascii_uppercase + string.digits, k=6))
                code = ''.join(secrets.choice('0123456789') for _ in range(6))

                # use language_code from user_info if available, otherwise default to 'da'
                language_code: str = user_info.get('language_code')
                logger.info(f'User language_code: {language_code}')
                if not language_code:
                    language_code = 'da'
                logger.debug(f'Using language_code: {language_code}')

                # Save `service`, `verification_code`, `chat_id`, and `expires_at` into pending document
                res: str = save_pending_link(str(chat_id), code, name, 'telegram', language_code)

                # send message with linking code back to the user via Telegram Bot API
                msg_text: str = ''
                if res == code:
                    # message the code back to the user instantly
                    msg_text = i18n.t('app.service_link_code', code=code, name=name, service_name='Telegram', locale=language_code)
                else:
                    # res is a string value for a localized error message
                    msg_text = i18n.t(res, locale=language_code)
                logger.info('Sending code to Telegram user')
                logger.debug(f'Message: {msg_text}')
                msg_text = escape_markdown_v2(msg_text)  # escape MarkdownV2
                msg_text = msg_text.replace(f'{code}', f'`{code}`')  # add bacticks to the message for tap to copy in Telegram
                logger.debug(f'Sending message to Telegram user {chat_id}: {msg_text}')
                msg_payload = {
                    'chat_id': chat_id,
                    'text': msg_text,
                    'parse_mode': 'MarkdownV2',
                    'reply_markup': {
                        'inline_keyboard': [
                            [
                                {
                                    'text': f'📋 {i18n.t("app.copy_code")}',
                                    'copy_text': {
                                        'text': code  # <--- ONLY the 6-digit string gets copied when tapped
                                    },
                                }
                            ]
                        ]
                    },
                }
                msg_url = f'https://api.telegram.org/bot{os.environ.get("EIR_TELEGRAM_TOKEN")}/sendMessage'
                headers = {'Content-Type': 'application/json'}
                tg_response = requests.post(msg_url, json=msg_payload, headers=headers, timeout=REQUEST_TIMEOUT)
                logger.info(f'Response from Telegram: {tg_response.status_code}')
                logger.debug(tg_response.json())
            else:
                logger.info(f'Ignoring message from Telegram user {chat_id}: {text}')
        except Exception as e:
            logger.error(f'Error sending message to Telegram user {chat_id}: {e}')
    return jsonify({'status': 'ok'}), 200


def send_telegram_message(chat_id: str, notification_text: str, **kwargs) -> bool:
    # anything irrelevant in the kwargs just gets ignored
    token = os.environ.get('EIR_TELEGRAM_TOKEN')
    if not token:
        logger.error('EIR_TELEGRAM_TOKEN not set')
        return False

    url = f'https://api.telegram.org/bot{token}/sendMessage'

    # Clean, basic payload—no markdown parser to trip over
    payload = {
        'chat_id': chat_id,
        'text': notification_text,
    }

    logger.debug(payload)
    try:
        response: requests.Response = requests.post(url, json=payload, timeout=REQUEST_TIMEOUT)
        logger.info(f'Response from Telegram: {response.status_code}')
        data = response.json()
        logger.debug(data)
        return data.get('ok', False)
    except ValueError:
        logger.warning(f'Non-JSON response body from Telegram: {response.text}')
    except requests.exceptions.RequestException as e:
        logger.error(f'Failed to reach Telegram: {e}')
    return False


def escape_markdown_v2(text: str) -> str:
    """Escapes all reserved characters for Telegram MarkdownV2 parsing."""
    # List of all 18 reserved characters: _ * [ ] ( ) ~ ` > # + - = | { } . !
    escape_chars = r'_*[]()~`>#+-=|{}.!'
    return re.sub(f'([{re.escape(escape_chars)}])', r'\\\1', text)


