@app.route('/boxcheck', methods=['POST', 'OPTIONS'])
@require_session_keys('PHPSESSID', 'username', 'teams', redirect_to='login_c')
def boxcheck() -> ResponseReturnValue:
    """Get around js security when setting the checkbox value in Conventus"""
    origin: str = request.headers.get('Origin', '')
    logger.debug(f'boxcheck request from origin: {origin}')
    my_app = False
    if 'http://localhost' == origin or '/localhost:' in origin or '127.0.0.1' in origin or 'eir-qkcv.onrender.com' in origin:
        my_app = True

    # Handle the CORS pre-flight handshake
    if request.method == 'OPTIONS':
        res = make_response()
        if my_app:
            res.headers['Access-Control-Allow-Origin'] = origin
            res.headers['Access-Control-Allow-Methods'] = 'POST, OPTIONS'
            res.headers['Access-Control-Allow-Headers'] = 'Content-Type'
        return res

    # Logic for the actual POST
    if my_app:
        phpsessid = session.get('PHPSESSID')
        logger.trace(f'sessid: {phpsessid}')
        real_response_text = ''
        try:
            real_response_text = conventus.passthru_check_action(request, phpsessid)
            # real_response_text = conventus.passthru_check_action_fake(request)
        except Exception as e:
            logger.exception(f'Failed to set checkbox: {e}')
            real_response_text = 'fail'
        logger.trace(f'response from conventus: {real_response_text}')

        # Respond back to our JavaScript
        res = make_response(real_response_text)
        res.headers['Access-Control-Allow-Origin'] = origin
        return res

    return make_response('fail', 403)


def team_id_to_ref(team_id: str, session_key: str) -> str:
    """Convert team_id to team_ref using the teams stored in the session. NB: Requires the session key because it is used by both coach and member."""
    teams: list = session.get(session_key, [])
    for t in teams:
        logger.debug(f'team_id_to_ref processing team: {t}')
        if t.get('id') == team_id:
            ref = t.get('ref')
            # handle cases where the session data is not as expected
            if not ref:
                logger.error(f'Team ref not found for Team ID: {team_id}')
                raise SessionError(f'Team ref not found for Team ID: {team_id}')
            if type(ref) is not str:
                logger.error(f'Unexpected type for Team ref: {type(ref)}')
                raise SessionError(f'Unexpected type for Team ref: {type(ref)}')
            return ref
    logger.error('Team ID not in session teams')
    raise SessionError('Team ID not in session teams')


def team_ref_to_id(ref: str, session_key: str = 'teams') -> str:
    """Convert team_ref to team_id using the teams stored in the session"""
    teams: list = session.get(session_key, [])
    # from teams find team id from team name (passed as team)
    team_id = None
    for t in teams:
        logger.debug(f'team_ref_to_id processing team: {t}')
        if t.get('ref') == ref:
            team_id = t.get('id')
            # handle cases where the session data is not as expected
            if not team_id:
                logger.error(f'Team ID not found for {ref}')
                raise SessionError(f'Team ID not found for {ref}')
            if type(team_id) is not str:
                logger.error(f'Unexpected type for Team ID: {type(team_id)}')
                raise SessionError(f'Unexpected type for Team ID: {type(team_id)}')
            return team_id
    paired_teams: list[dict] = PAIRED_TEAMS  # later change to DB call
    for p in paired_teams:
        if p.get('name') == ref:
            team_id = get_paired_team_ids(ref, paired_teams)
            if not team_id:
                logger.error(f'Team IDs not found for {ref}')
                raise SessionError(f'Team ID not found for {ref}')
            if type(team_id) is not str:
                logger.error(f'Unexpected type for Team ID: {type(team_id)}')
                raise SessionError(f'Unexpected type for Team ID: {type(team_id)}')
            return team_id
    logger.error(f'Team ref {ref} not in session teams or paired teams')
    raise SessionError(f'Team ref {ref} not in session teams or paired teams')


